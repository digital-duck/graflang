"""`graf export-spl`: a graph written back as SPL. Needs nothing from SPL.py; the parse and round-trip checks run only if it is installed."""
from pathlib import Path

import pytest
from click.testing import CliRunner

from graphlang.cli import main
from graphlang.grafe.graph2spl import GraphToSPLError, graph_to_spl
from graphlang.grafr.runtime import load_graph

COOKBOOK = Path(__file__).parent.parent / "cookbook"
LIFTED = COOKBOOK / "chain_of_thought" / "chain_of_thought.graph.yaml"
TOOLED = COOKBOOK / "lifted_tool" / "lifted_tool.graph.yaml"
SELF_REFINE = COOKBOOK / "self_refine" / "self_refine.graph.yaml"


def test_a_lifted_graph_comes_back_with_its_functions():
    text, warnings = graph_to_spl(load_graph(LIFTED))
    assert warnings == []
    assert "CREATE FUNCTION analyze(research TEXT)" in text and "Research: {research}" in text
    assert "GENERATE research(@topic) INTO @research" in text and text.rstrip().endswith("RETURN @summary\nEND")


def test_a_lifted_tool_comes_back_as_create_tool_api():
    text, _ = graph_to_spl(load_graph(TOOLED))
    assert "CREATE TOOL_API shout(text TEXT, suffix TEXT)" in text and "CALL shout(@word, '!') INTO @loud" in text


def test_a_hand_written_generate_becomes_a_function_named_after_its_node():
    text, warnings = graph_to_spl(load_graph(SELF_REFINE))
    assert warnings == []
    assert "CREATE FUNCTION refine(essay TEXT, feedback TEXT)" in text and "GENERATE refine(@essay, @feedback)" in text
    assert "Original Essay:\n{essay}" in text


def test_what_spl_cannot_say_is_dropped_with_a_warning():
    graph = load_graph(LIFTED)
    graph["nodes"][1]["config"]["phases"] = {"exec": {"retry": {"max": 2}}}
    _, warnings = graph_to_spl(graph)
    assert any("'gen_1'" in w and "exec" in w for w in warnings)


def test_a_non_workflow_is_refused():
    with pytest.raises(GraphToSPLError):
        graph_to_spl({"workflow": {"name": "x"}, "nodes": [], "edges": []})


def test_the_command_writes_a_file(tmp_path):
    out = tmp_path / "chain.spl"
    result = CliRunner().invoke(main, ["export-spl", str(LIFTED), "-o", str(out)])
    assert result.exit_code == 0 and out.read_text().startswith("-- generated by `graf export-spl`")


# ---- only with SPL.py installed: the text is real SPL, and a lifted graph is a fixed point -------------------------------

def test_the_exported_text_parses_as_spl():
    pytest.importorskip("spl3.parser")
    from spl.lexer import Lexer
    from spl3.parser import SPL3Parser
    for path in (LIFTED, TOOLED, SELF_REFINE):
        text, _ = graph_to_spl(load_graph(path))
        statements = SPL3Parser(Lexer(text).tokenize()).parse().statements
        assert any(type(s).__name__ == "WorkflowStatement" for s in statements), path


@pytest.mark.parametrize("path", [LIFTED, TOOLED], ids=lambda p: p.parent.name)
def test_lifting_the_export_gives_the_graph_back(path):
    pytest.importorskip("spl3.spl2graph")
    from spl3.spl2graph import spl_to_graph
    graph = load_graph(path)
    for node in graph["nodes"]:
        node.pop("port_types", None)                              # added on load from the input types, not part of the file
    text, _ = graph_to_spl(graph)
    again, _ = spl_to_graph(text)
    assert _diff(_canonical({k: graph[k] for k in ("workflow", "nodes", "edges")}),
                 _canonical({k: again[k] for k in ("workflow", "nodes", "edges")})) == []


def _canonical(graph):
    """Edge order carries no meaning: sort every edge list (also inside LOOP subgraphs)."""
    if isinstance(graph, dict):
        out = {k: _canonical(v) for k, v in graph.items()}
        if isinstance(out.get("edges"), list):
            out["edges"] = sorted(out["edges"], key=lambda e: (e["type"], e["source"], e["target"]))
        return out
    if isinstance(graph, list):
        return [_canonical(x) for x in graph]
    return graph


def _diff(a, b, path: str = "") -> list[str]:
    if type(a) is not type(b):
        return [f"{path or '/'}: {a!r} != {b!r}"]
    if isinstance(a, dict):
        out = []
        for k in dict.fromkeys([*a, *b]):
            if k not in a or k not in b:
                out.append(f"{path}/{k}: only in {'first' if k in a else 'second'}")
            else:
                out += _diff(a[k], b[k], f"{path}/{k}")
        return out
    if isinstance(a, list):
        if len(a) != len(b):
            return [f"{path}: length {len(a)} != {len(b)}"]
        return [d for i, (x, y) in enumerate(zip(a, b)) for d in _diff(x, y, f"{path}[{i}]")]
    return [] if a == b else [f"{path}: {a!r} != {b!r}"]
